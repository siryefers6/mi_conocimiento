"""
Objetivo: Comparar si un valor es menor o igual que otro
Referencia: <=
Tipo: operador
Nivel: basico
"""

# menor o igual
a = 5
b = 10
print("¿5 <= 10?", a <= b)

x = 15
y = 15
print("¿15 <= 15?", x <= y)

z = 20
w = 10
print("¿20 <= 10?", z <= w)

"""output
¿5 <= 10? True
¿15 <= 15? True
¿20 <= 10? False
"""
