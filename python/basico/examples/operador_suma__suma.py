"""
Objetivo: Sumar dos o más números
Referencia: +
Tipo: operador
Nivel: basico
"""

# suma
a = 10
b = 5
resultado = a + b
print("Suma:", resultado)

# suma múltiple
x = 2 + 3 + 4
print("Múltiple:", x)

# suma strings
texto = "Hola" + " " + "mundo"
print("Concatenación:", texto)

"""output
Suma: 15
Múltiple: 9
Concatenación: Hola mundo
"""
