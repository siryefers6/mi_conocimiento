"""
Objetivo: Generar secuencia de números para iterar
Referencia: range
Tipo: función
Nivel: basico
"""

# range simple (0 a n-1)
for i in range(3):
    print(i)

print("---")

# range con inicio y fin
for i in range(2, 5):
    print(i)

print("---")

# range con paso
for i in range(0, 10, 2):
    print(i)

"""output
0
1
2
---
2
3
4
---
0
2
4
6
8
"""
