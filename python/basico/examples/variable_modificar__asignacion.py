"""
Objetivo: Cambiar el valor de una variable existente
Referencia: =
Tipo: operador
Nivel: basico
"""

# modificar variable
contador = 0
print("Inicial:", contador)

contador = 5
print("Modificado:", contador)

contador = contador + 1
print("Incrementado:", contador)

"""output
Inicial: 0
Modificado: 5
Incrementado: 6
"""
