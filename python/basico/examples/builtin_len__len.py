"""
Objetivo: Obtener la longitud de una secuencia
Referencia: len
Tipo: función
Nivel: basico
"""

# largo de lista
lista = [1, 2, 3, 4, 5]
print(f"Lista: {len(lista)}")

# largo de string
texto = "Hola"
print(f"String: {len(texto)}")

# largo de diccionario
datos = {"a": 1, "b": 2}
print(f"Diccionario: {len(datos)}")

# largo de tupla
tupla = (10, 20, 30)
print(f"Tupla: {len(tupla)}")

"""output
Lista: 5
String: 4
Diccionario: 2
Tupla: 3
"""
