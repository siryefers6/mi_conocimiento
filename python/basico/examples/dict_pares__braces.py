"""
Objetivo: Crear un diccionario con pares clave-valor
Referencia: {}
Tipo: literal
Nivel: basico
"""

# diccionario simple
libro = {"título": "Python 101", "autor": "Juan", "año": 2023}
print(libro)

# diccionario con tipos mixtos
datos = {"nombre": "Ana", "edad": 30, "activo": True, "saldo": 1500.50}
print(datos)

# diccionario vacío
d = dict()
print("Vacío con dict():", d)

