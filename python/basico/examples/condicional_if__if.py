"""
Objetivo: Ejecutar código si una condición es verdadera
Referencia: if
Tipo: keyword
Nivel: basico
"""

# if simple
edad = 18
if edad >= 18:
    print("Es mayor de edad")

# sin condición cumplida
calificacion = 5
if calificacion >= 6:
    print("Aprobado")

# con expresiones
numero = 10
if numero > 0 and numero < 20:
    print("Está entre 0 y 20")

"""output
Es mayor de edad
Está entre 0 y 20
"""
