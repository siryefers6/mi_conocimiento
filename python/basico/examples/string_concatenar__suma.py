"""
Objetivo: Unir múltiples cadenas de texto
Referencia: +
Tipo: operador
Nivel: basico
"""

# concatenación simple
a = "Hola"
b = "mundo"
resultado = a + " " + b
print(resultado)

# concatenación múltiple
nombre = "Ana"
apellido = "García"
edad = 28
saludo = "Nombre: " + nombre + " " + apellido + ", edad: " + str(edad)
print(saludo)

"""output
Hola mundo
Nombre: Ana García, edad: 28
"""
