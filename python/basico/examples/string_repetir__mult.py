"""
Objetivo: Repetir una cadena de texto múltiples veces
Referencia: *
Tipo: operador
Nivel: basico
"""

# repetir string
simbolo = "*"
linea = simbolo * 10
print(linea)

# repetir palabra
palabra = "na"
resultado = palabra * 3
print(resultado)

# crear patrón
patron = "ab"
repetido = patron * 4
print(repetido)

