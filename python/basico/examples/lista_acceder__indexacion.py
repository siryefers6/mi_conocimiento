"""
Objetivo: Acceder a elementos de una lista por su índice
Referencia: []
Tipo: operador
Nivel: basico
"""

# acceder por índice positivo
frutas = ["manzana", "plátano", "cereza"]
print("Primer elemento:", frutas[0])
print("Segundo elemento:", frutas[1])

# acceder por índice negativo
print("Último elemento:", frutas[-1])
print("Penúltimo:", frutas[-2])

"""output
Primer elemento: manzana
Segundo elemento: plátano
Último elemento: cereza
Penúltimo: plátano
"""
