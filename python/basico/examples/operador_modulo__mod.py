"""
Objetivo: Obtener el resto de una división
Referencia: %
Tipo: operador
Nivel: basico
"""

# módulo
a = 17
b = 5
resto = a % b
print("Resto:", resto)

# verificar si es par
numero = 10
if numero % 2 == 0:
    print(f"{numero} es par")
else:
    print(f"{numero} es impar")

"""output
Resto: 2
10 es par
"""
