"""
Objetivo: Crear una tupla con elementos
Referencia: ()
Tipo: literal
Nivel: basico
"""

# tupla de strings
frutas = ("manzana", "plátano", "cereza")
print(frutas)

# tupla mixta
datos = (1, "texto", 3.14, True)
print(datos)

# tupla anidada
matriz = ((1, 2), (3, 4), (5, 6))
print(matriz)

