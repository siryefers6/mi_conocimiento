"""
Objetivo: Crear una tupla
Referencia: ()
Tipo: literal
Nivel: basico
"""

# tupla vacía
vacia = ()
print("Tupla vacía:", vacia)
print("Tipo:", type(vacia))

# tupla con elementos
numeros = (1, 2, 3, 4, 5)
print("Números:", numeros)

# tupla sin paréntesis
tupla = 10, 20, 30
print("Sin paréntesis:", tupla)

# tupla de un elemento (requiere coma)
una = (42,)
print("Un elemento:", una)

