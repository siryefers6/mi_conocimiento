"""
Objetivo: Obtener el valor absoluto
Referencia: abs
Tipo: función
Nivel: basico
"""

# valor absoluto de negativos
numero = -5
absoluto = abs(numero)
print(f"abs(-5) = {absoluto}")

# valor absoluto de positivos
numero2 = 10
print(f"abs(10) = {abs(numero2)}")

# con decimales
numero3 = -3.14
print(f"abs(-3.14) = {abs(numero3)}")

"""output
abs(-5) = 5
abs(10) = 10
abs(-3.14) = 3.14
"""
