"""
Objetivo: Ejecutar código alternativo si if es falso
Referencia: else
Tipo: keyword
Nivel: basico
"""

# if-else
edad = 16
if edad >= 18:
    print("Mayor de edad")
else:
    print("Menor de edad")

# otro ejemplo
numero = -5
if numero > 0:
    print("Positivo")
else:
    print("No positivo")

"""output
Menor de edad
No positivo
"""
