"""
Objetivo: Dividir números sin decimales (resultado entero)
Referencia: //
Tipo: operador
Nivel: basico
"""

# división entera
a = 17
b = 5
resultado = a // b
print("División entera:", resultado)

# comparar con división normal
print("Normal:", 17 / 5)
print("Entera:", 17 // 5)

"""output
División entera: 3
Normal: 3.4
Entera: 3
"""
