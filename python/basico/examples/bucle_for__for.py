"""
Objetivo: Iterar sobre una secuencia con for
Referencia: for
Tipo: keyword
Nivel: basico
"""

# for sobre lista
frutas = ["manzana", "plátano", "cereza"]
for fruta in frutas:
    print(fruta)

print("---")

# for sobre string
for letra in "hola":
    print(letra)

