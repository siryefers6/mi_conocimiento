"""
Objetivo: Crear cadenas de texto usando comillas
Referencia: "" o ''
Tipo: literal
Nivel: basico
"""

# strings con comillas dobles
texto1 = "Hola mundo"
print(texto1)

# strings con comillas simples
texto2 = 'Python es genial'
print(texto2)

# strings vacíos
vacio = ""
print(f"Vacío: '{vacio}'")

# strings multilinea
parrafo = """Este es
un texto
en múltiples líneas"""
print(parrafo)

"""output
Hola mundo
Python es genial
Vacío: ''
Este es
un texto
en múltiples líneas
"""
