"""
Objetivo: Generar secuencia de números
Referencia: range
Tipo: función
Nivel: basico
"""

# range básico (0 a n-1)
print(list(range(3)))

# range con inicio y fin
print(list(range(2, 5)))

# range con paso
print(list(range(0, 10, 2)))

# range invertido
print(list(range(5, 0, -1)))

"""output
[0, 1, 2]
[2, 3, 4]
[0, 2, 4, 6, 8]
[5, 4, 3, 2, 1]
"""
