"""
Objetivo: Comparar si dos valores son iguales
Referencia: ==
Tipo: operador
Nivel: basico
"""

# comparación igual
a = 5
b = 5
resultado = a == b
print("¿5 == 5?", resultado)

x = 10
y = 20
resultado = x == y
print("¿10 == 20?", resultado)

# comparación de strings
texto1 = "Hola"
texto2 = "Hola"
print("¿'Hola' == 'Hola'?", texto1 == texto2)

"""output
¿5 == 5? True
¿10 == 20? False
¿'Hola' == 'Hola'? True
"""
