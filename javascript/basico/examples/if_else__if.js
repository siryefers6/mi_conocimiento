/**
 * Objetivo: bifurcación condicional con alternativa
 * Referencia: if...else
 * Tipo: keyword
 * Nivel: básico
 */

// If/else básico
const numero = 10;

if (numero > 0) {
    console.log("El número es positivo");
} else {
    console.log("El número es negativo o cero");
}

// If/else con variable
const hora = 14;

if (hora < 12) {
    console.log("Buenos días");
} else {
    console.log("Buenos tardes o noches");
}

// If/else con lógica
const acceso = true;

if (acceso) {
    console.log("Acceso permitido");
} else {
    console.log("Acceso denegado");
}

/*
output
El número es positivo
Buenos tardes o noches
Acceso permitido
*/
